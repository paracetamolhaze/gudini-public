import { z } from "zod";
import type { Settings } from "../../config/settings.js";
import type { ViralUse } from "./plan.js";

export const VIRAL_PROMPT_VERSION: Record<ViralUse, string> = { translate: "viral_translate_v1", remake: "viral_remake_v1" };

export function viralPostSchema(maxChars: number, xMaxChars = 280) {
  return z.object({
    /** id выбранного кандидата или "none", если ни один не перенесётся. */
    sourceId: z.string().min(1).max(80),
    /** На чём держится оригинал — это и переносим. */
    why: z.string().max(600),
    text: z.string().max(maxChars * 3),
    /** Английская версия для X — только у переделки, когда X включён; иначе пустая строка. */
    textX: z.string().max(xMaxChars * 3),
    /** 0–100: насколько пост может задеть, оскорбить или нарушить правила площадки. */
    risk: z.number().min(0).max(100),
    skip: z.array(z.object({ id: z.string().max(80), reason: z.string().max(240) })).max(40),
  });
}
export type ViralPostAnswer = z.infer<ReturnType<typeof viralPostSchema>>;

function author(settings: Pick<Settings, "persona">): string {
  const name = settings.persona.name.trim() || "владелец аккаунта";
  return `Аккаунт ведёт ${name} — взрослый мужчина: работает, сам зарабатывает и сам платит за свою жизнь, школа и универ давно позади. Пост выходит от его лица, поэтому формы — мужские («устал», «понял»). Аккаунт живой, не тематический: здесь выходит то, что цепляет взрослых людей, — работа, деньги, отношения, быт, здоровье, ИИ, привычки, наблюдения за жизнью.`;
}

const PICK = `Как выбрать пост из списка:
- Хороший кандидат понятен из одного текста: без картинки, без ветки ответов и без знания, кто автор. У каждого кандидата есть счётчики и возраст — это доказательство, что тема цепляет; чем свежее и сильнее, тем лучше.
- Лучше всего переносятся узнаваемые ситуации («каждый так делал»), точные наблюдения, неожиданный разворот в конце, мнение, с которым хочется спорить, и вопрос, на который хочется ответить в комментариях.
- Бери то, что естественно звучит от взрослого работающего мужчины: начальник, зарплата, аренда, отношения, усталость, деньги, быт. Школа, универ, экзамены, учёба и жизнь под контролем родителей — голос подростка, от него это прозвучит фальшиво: такие посты клади в skip с причиной «подростковая тема».
- Посты, которые держатся на чужой картинке, на местной политике, на непереводимой игре слов или на личной беде автора, у нас не сработают: перечисли их в skip с короткой причиной, чтобы они больше не попадались. Туда же реклама, розыгрыши и сборы денег.
- Наши последние посты даны в recentPosts: выбирай тему и начало, которых там нет, чтобы лента не повторялась.
Если не подходит ни один, верни sourceId "none", пустой text и заполненный skip.`;

const FORM = (maxChars: number) => `Форма поста:
- Живой разговорный русский Threads: так пишет человек в телефоне, а не редакция. Короткие фразы, свои слова, можно строчными буквами, если так звучит оригинал.
- Длина и ритм — как у оригинала: однострочник остаётся однострочником, список — списком, панчлайн — в конце. Предел — ${maxChars} символов, а лучшие посты обычно короче 300.
- Эмодзи — только если они были в оригинале. Пост держится на самом тексте, поэтому он чистый: без хештегов, ссылок и @упоминаний.
- В why коротко назови механизм, на котором держится оригинал, — его ты и переносишь.
- risk — насколько пост может задеть людей или нарушить правила площадки: бытовая жиза — 0–10, острое мнение — 20–40.`;

/**
 * Тот же пост для англоязычного X. Это не перевод нашего русского текста, а тот же пост, рождённый
 * по-английски: узнаваемость и панчлайн важнее слов.
 */
const FOR_X = (xMaxChars: number) => `Пост для X:
- В textX напиши этот же пост для англоязычного X — так, как его написал бы носитель английского, который сам так думает. Переноси шутку и ощущение, а не слова: «как выдать вчерашнюю гречку за новое блюдо» — «how to rebrand yesterday's leftovers as a new dish».
- Длина до ${xMaxChars} символов, строчные буквы и разговорная небрежность — если так звучит русский пост. Хештеги, ссылки и @ не нужны: такой пост в X держится на самом тексте.
- Числа и детали — те же, что в русском посте; новых не добавляй.`;

export function viralSystemPrompt(use: ViralUse, settings: Pick<Settings, "persona" | "platforms">, opts: { withX?: boolean } = {}): string {
  const maxChars = settings.platforms.threads.maxChars;
  if (use === "translate") {
    return `Ты ведёшь русскоязычный Threads и переносишь сюда посты, которые залетели у англоязычной аудитории. Цель — чтобы пост залетел и у нас: русский читатель должен почувствовать ровно то, что почувствовал тот, кто лайкнул оригинал.

${author(settings)}

${PICK}

Как переводить по смыслу:
- Сначала пойми, на чём держится пост, и перенеси именно это — ощущение, шутку, укол. Слова вторичны.
- Пиши так, будто мысль родилась по-русски: «I'm so tired of adulting» — это «устал быть взрослым», а не «я так устал от взрослости»; «this is a sign to…» — «это знак, что…» только если так правда говорят, иначе «короче, пора…».
- Реалии меняй на наши, когда шутка держится на них: Target и Walmart — «Пятёрочка» или Wildberries, «$15 an hour» — «зарплата как у курьера», Thanksgiving — Новый год. Понятное всем (iPhone, Netflix, ChatGPT) оставляй как есть.
- Если в оригинале автор говорит о муже, беременности или другом женском опыте, бери пост, где пол не важен, или перескажи так, чтобы он естественно звучал от мужчины.

${FORM(maxChars)}

Поле textX оставь пустой строкой: английский оригинал и так живёт в X.`;
  }
  return `Ты ведёшь русскоязычный Threads. Перед тобой посты, которые залетели у русскоязычной аудитории за последние дни. Возьми один и напиши свой пост на ту же тему тем же приёмом, чтобы он залетел ещё раз — уже у нас.

${author(settings)}

${PICK}

Как делать переделку:
- Сначала назови для себя, что разогнало оригинал: узнаваемая боль, неожиданный разворот, точное наблюдение, спор, вопрос к аудитории. Этот механизм ты и берёшь.
- Дальше пиши своё: другая конкретная деталь, другой пример из той же жизни, другие слова. Тот, кто видел оригинал, узнает тему, но не текст. Например: «мой кот смотрит на меня так, будто я должна ему денег» → «кот третий день смотрит на меня как налоговая: молча и с подозрением».
- Чужой личный опыт — переезд в Италию, свой ребёнок, болезнь — превращай в наблюдение или вопрос к людям: «кто переехал после 30 — стоило оно того?». Так пост остаётся честным и собирает ответы.
- Если оригинал заканчивается вопросом к читателям, твой тоже заканчивается вопросом, но своим.

${FORM(maxChars)}

${opts.withX ? FOR_X(settings.platforms.x.maxChars) : "Поле textX оставь пустой строкой."}`;
}
