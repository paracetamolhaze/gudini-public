/**
 * Режиссёр «Опус 5.5»: Claude читает речь автора (слова с номерами и временем) и подбирает к ней настоящие кадры —
 * официальные видео с YouTube, страницы сайтов с фразой под маркером, фото людей, логотипы, числа, карту, мемы.
 * Сам автор в кадре — между ними: монтаж в духе «Новостей», только голос и лицо — из записи владельца.
 */
import { claudeJson } from "../pipeline/llm";
import { memeCatalog } from "../pipeline/plan";

export type OpusWord = { w: string; s: number; e: number };

export type OpusShot =
  | { word: number; show: "owner" }
  | { word: number; show: "footage"; url: string; at: number; what: string }
  | { word: number; show: "screen"; url: string; phrase: string; what: string }
  | { word: number; show: "chart"; coin: string; slug: string; date: string; amount: number; price: number };

export type OpusDraft = {
  shots: OpusShot[];
  numbers?: { word: number; value: number; prefix?: string; suffix?: string; label?: string }[];
  people?: { word: number; name: string }[];
  logos?: { word: number; brand: string; domain: string }[];
  places?: { word: number; country: string; name?: string }[];
  memes?: { word: number; meme: string; why: string }[];
  accents?: { word: number; kind: "kick" | "boom" | "glitch" | "cash" }[];
};

const SYSTEM = `Ты монтажёр коротких вертикальных роликов про крипту и деньги, в духе TikTok-новостей: автор говорит в камеру, а каждое его утверждение тут же подтверждается настоящим кадром. Запись автора уже есть — его голос звучит без перерыва от начала до конца, ты решаешь, что зритель видит в каждую секунду.

Что бывает в кадре:
- owner — сам автор, его лицо из записи (звук и губы совпадают). Он ведёт ролик: зацепка, личные оценки, вывод, обращение к зрителю.
- footage — кусок настоящего видео с YouTube: официальная презентация, репортаж, выступление, реклама тех лет. url — ссылка на конкретное видео (youtube.com/watch?v=…), at — примерная секунда нужного момента (точную подберут по кадрам ролика). Подбирай видео, у которого знаешь содержание, с чистой картинкой без бегущих строк чужих телеканалов: официальные каналы компаний, новостные выпуски, где момент можно найти по описанию, главам или расшифровке. what — что именно видно в кадре («Тим Кук показывает iPhone X на сцене»).
- screen — настоящая страница сайта, каждая страница в ролике один раз: новость, архивная статья, страница биржи или курса. url — адрес страницы (для старых новостей подходит снимок из web.archive.org), phrase — дословный кусок текста этой страницы из 3–10 слов, его выделит жёлтый маркер: дата, цена, заголовок — то, о чём в эту секунду говорит автор. what — что на странице.

- chart — наш график: во что превращалось вложение от дня покупки до сегодня, линия рисуется, сумма растёт, в конце итог. coin — название по-русски («Биткоин»), slug — адрес монеты на CoinMarketCap (bitcoin, ethereum, official-trump, dogecoin, shiba-inu, pepe, solana, bnb, notcoin), date — день покупки ГГГГ-ММ-ДД, amount — вложенная сумма в долларах, price — цена монеты в день покупки из речи автора. Ставь его на итог («сегодня… твой доллар превратился бы…») и держи 3–5 секунд: это главный кадр ролика, когда в речи есть вложение и итог.

Поверх любого кадра можно добавить:
- numbers — крупное число отсчётом на слове, где оно звучит: сумма, курс, проценты (value — цифрами, prefix «$», suffix «%», label — 2–3 слова подписи).
- people — фото известного человека, которого называют, а в кадре его нет (name — статья английской Википедии).
- logos — логотип бренда на слове, где его называют (brand и domain — сайт бренда).
- places — страна на карте (country — код ISO из двух латинских букв, name — по-русски).
- memes — мем-реакция из каталога (meme — id), когда зритель в эту секунду должен засмеяться или ахнуть; why — какая реакция.
- accents — удар на слове-развороте: kick — лёгкий толчок, boom — тряска со звуком, cash — звук денег на сумме, glitch — сбой на «но вот чего не покажут».

Как строится хороший ролик (рубрика «Сколько бы у тебя было»: «вместо айфона в 2017-м купил бы биткоин»):
1. Первые 2–3 секунды — автор в кадре с зацепкой, или сразу самый яркий кадр истории, если зацепка про него («вышел айфон десять» — презентация с ценой на экране).
2. Каждое проверяемое утверждение — свой кадр-доказательство: «биткоин стоил семь с половиной тысяч» — страница новости того дня с ценой под маркером; «сегодня это десять тысяч долларов» — число отсчётом поверх автора; «через год упал до трёх тысяч двухсот» — архивная новость о падении.
3. Автор в кадре — на зацепке, на своих выводах и на последней фразе; в остальное время картинка меняется каждые 2–4 секунды, и автор подряд держится не дольше 4 секунд. На минуту речи — 10–14 кадров-доказательств, из них 2–4 куска настоящего видео: ролик живой, когда в нём движутся люди и события, а не только страницы.
4. Образ-сравнение автора («как одна крошка от целого пирога», «полный стадион») показывает мем или кадр, который этот образ передаёт.
5. Кадры меняются на словах, которые их называют, и держатся 1,5–4 секунды: столько нужно, чтобы прочитать фразу под маркером. Фразу для маркера бери из заголовка или первого абзаца статьи — тогда на снимке видна и шапка сайта с логотипом.

Ответ — только JSON:
{"shots":[{"word":0,"show":"owner"},{"word":9,"show":"footage","url":"https://www.youtube.com/watch?v=…","at":4980,"what":"…"},{"word":21,"show":"screen","url":"https://web.archive.org/web/2017…/…","phrase":"…","what":"…"},{"word":30,"show":"owner"},{"word":44,"show":"chart","coin":"Биткоин","slug":"bitcoin","date":"2017-11-03","amount":1000,"price":7200}],
 "numbers":[{"word":40,"value":10800,"prefix":"$","label":"сегодня"}],"people":[],"logos":[{"word":5,"brand":"Apple","domain":"apple.com"}],"places":[],"memes":[],"accents":[{"word":52,"kind":"glitch"}]}
word — номер слова речи, на котором кадр начинается; shots идут по возрастанию word, первый — со слова 0. Ссылки и фразы проверь поиском: страница открывается, фраза на ней есть дословно. Кадр, для которого не нашлось настоящего источника, оставь автору.`;

export async function direct(words: OpusWord[], topic: string, script: string): Promise<OpusDraft> {
  // слова с номерами и временем, по фразе на строку: Claude видит, сколько секунд держится каждый кадр
  const lines: string[] = [];
  let cur: string[] = [];
  words.forEach((w, i) => {
    cur.push(`${i}:${w.w}`);
    if (/[.!?…]$/.test(w.w) || cur.length >= 14 || i === words.length - 1) {
      lines.push(`[${words[i - cur.length + 1].s.toFixed(1)}–${w.e.toFixed(1)} с] ${cur.join(" ")}`);
      cur = [];
    }
  });
  const memes = memeCatalog()
    .map((m) => `${m.id} — ${m.name}: ${m.situation}`)
    .join("\n");
  const user = `Тема ролика: «${topic}»
${script ? `Сценарий автора (для смысла; монтаж — по словам речи ниже):\n${script}\n` : ""}
Речь автора по словам (номер:слово), длина ${words.at(-1)?.e.toFixed(1)} с:
${lines.join("\n")}

Каталог мемов:
${memes}

Разложи ролик по кадрам.`;
  const draft = await claudeJson<OpusDraft>(SYSTEM, user, { web: true, task: "opus-director", effort: "high" });
  if (!draft || !Array.isArray(draft.shots)) throw new Error("Режиссёр «Опус 5.5» не вернул раскладку кадров");
  return draft;
}

/** Проверка добытых кадров глазами: на картинке то, что обещал режиссёр, а не заглушка, капча или чужое видео. */
export async function confirm(items: { what: string; image: string; mediaType: string }[]): Promise<boolean[]> {
  if (!items.length) return [];
  const system = `Ты проверяешь кадры для монтажа. Для каждой картинки по порядку ответь, показывает ли она обещанное: настоящий кадр видео или страница сайта с нужным содержанием. У видео на картинке три кадра куска подряд (начало, середина, конец): true, если обещанное видно на большей части куска. Заглушка «видео недоступно», капча, окно входа, пустая страница, ошибка 404, совсем другое содержание, а у видео — эфир чужого телеканала с бегущей строкой и плашками или черно-белый сток — false. Ответ — только JSON {"ok":[true,false,…]}.`;
  const user = items.map((x, i) => `${i + 1}. Обещано: ${x.what}`).join("\n");
  const answer = await claudeJson<{ ok: boolean[] }>(system, user, { task: "opus-check", effort: "low", images: items.map((x) => ({ base64: x.image, mediaType: x.mediaType })) });
  return items.map((_, i) => answer?.ok?.[i] === true);
}
