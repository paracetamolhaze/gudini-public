import fs from "node:fs";
import path from "node:path";
import { MEDIA_ROOT } from "./util";

export type Feature =
  /** звуки одной роли чередуются, а не звучит всегда первый файл папки */
  | "sfxVariety"
  /** видеомемы с высоким риском Content ID (узнаваемая музыка правообладателя) режиссёру не предлагаются */
  | "contentId"
  /** проверка готового ролика: замершие и чёрные кадры, громкость, лист кадров (по motion-video-kit) */
  | "qc"
  /** свежий критик смотрит лист кадров готового ролика и ставит оценку — он ролик не монтировал */
  | "critic"
  /** план истории до раскладки: что обещаем зрителю, главный вопрос, что меняет каждый кусок (по video-recap-skills) */
  | "storyPlan"
  /** обводки и стрелки от руки на детали в кадре */
  | "marks"
  /** логотип собирается на экране, а не просто выскакивает (по pixel2motion) */
  | "logoReveal"
  /** переписка пузырями по-русски вместо снимка чата */
  | "chats"
  /** крупное число отсчётом на слове, где оно звучит */
  | "numbers"
  /** карта со страной события */
  | "maps"
  /** видеомем поверх ролика без размытых полей и, где люди, без фона (vmeme_prep.py) — иначе во весь экран, как был */
  | "vmemeOverlay"
  /** заготовка лучших историй запаса в фоне до сценария включительно (prep.ts) — «Монтировать» начинает с голоса */
  | "prep"
  /** опыт на YouTube: крипто-ролики выходят вариантами по кругу — с телеграмом и без, со спокойным названием (trial.ts) */
  | "ytTrial"
  /** видеомемы в новых роликах; владелец 10.11 выключил: в news/features.json стоит false */
  | "videoMemes"
  // 11.11, по motionmaxxing, video-shotcraft и video-talkcraft — каждое выключается отдельно, ключа в файле нет — включено:
  /** вставки двигаются по измеренным числам: приход из увеличенного или от края с замедлением, уход с ускорением, без отскока */
  | "motion"
  /** привязка к слову: вставка к началу слова уже стоит, число встаёт на слово-число, итог графика «Опуса» — на слово с суммой */
  | "wordSync"
  /** пока деталь обведена овалом, остальной кадр чуть притемнён */
  | "markFocus"
  /** «Опус»: маркер на снимке страницы проводится по строке на глазах, а не нарисован заранее */
  | "screenSweep"
  /** проверка вставок по плану готового ролика: стоит без движения, не на своём слове, обрезана, наложилась — в qc.json и журнал */
  | "qcInserts"
  /** критик видит крупные кадры вставок и судит, событие в кадре или слайд */
  | "qcSlides";

let cache: { stamp: string; values: Record<string, unknown> } | null = null;

export function on(name: Feature): boolean {
  const file = path.join(MEDIA_ROOT, "features.json");
  try {
    const st = fs.statSync(file);
    const stamp = `${st.size}:${st.mtimeMs}`;
    if (cache?.stamp !== stamp) cache = { stamp, values: JSON.parse(fs.readFileSync(file, "utf8")) as Record<string, unknown> };
  } catch {
    cache = null;
  }
  return cache?.values[name] !== false;
}
