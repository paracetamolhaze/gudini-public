export function researchTask(today: string, done: { title: string; key: string; at: string }[]): { system: string; user: string } {
  const doneList = done.length ? done.map((t) => `- ${t.title} (${t.key}, ${t.at.slice(0, 10)})`).join("\n") : "- пока нет";
  return {
    system: VOICE,
    user: `Сегодня ${today}. Найди одну историю для новой карусели и собери по ней факты.

Какая история подходит:
- она про деньги самого читателя: про кошелёк, биржу, стейблкоин, приложение или правило, которыми он пользуется сам (Binance, Bybit, OKX, USDT, Telegram Wallet и TON, MetaMask, Trust Wallet, Phantom, Ledger, Trezor, телефон, банковская карта для P2P). Читатель смотрит на обложку и думает: «это про мой кошелёк, мои деньги, моё приложение». Так видно по просмотрам аккаунта: «В кошельках Ledger нашли чип-шпион» — 162 тыс. (у многих такой кошелёк), «Взлом Binance» — 17 тыс. (на Binance деньги читателей), «У USDT есть кнопка „заморозить“» — 5 тыс. (USDT есть почти у каждого). Суд по токену президента Аргентины и иск к Трампу набрали по 2 тыс.: это чужие разборки. Кража у малоизвестной бразильской биржи или у неназванной организации из ЕС проходит мимо: читатель о них не слышал;
- ${FORWARD};
- случилась или получила важное продолжение за последние 1–3 недели, лучше всего — за последние 7 дней;
- в ней есть загадка или конфликт вокруг того, чем пользуется читатель: скрытая функция или уязвимость, заморозка средств, утечка данных пользователей, новое правило биржи или закон, который меняет, как читатель хранит, покупает или выводит крипту, иск, расследование, странное движение денег;
- её можно разложить на 7 шагов «что известно» с цифрами, датами и именами, а в конце остаётся честный открытый вопрос — что пока неизвестно или не раскрыто;
- о ней писали минимум 4 независимых издания или есть первоисточники: документ суда, заявление компании, страница обозревателя блокчейна, репозиторий.

Эти истории уже были в аккаунте. Нужна история, которой в них не было ни главной темой, ни отдельным шагом, и не продолжение их:
${doneList}

Как собирать факты:
- ищи через WebSearch и открывай страницы через WebFetch; бери только то, что прочитал на странице сам;
- для каждого факта — точная цитата со страницы на языке оригинала, адрес именно статьи (не главной страницы), издатель и дата публикации;
- хорошие источники — новости крупных и профильных изданий (CoinDesk, The Block, Decrypt, Cointelegraph, Reuters, AP, BleepingComputer и т. п.), официальные заявления, обозреватели блокчейна, GitHub; страницы за пэйволлом (WSJ, Bloomberg, FT), посты в X, PDF и видео не подходят — их не открыть без входа;
- если источники расходятся в цифрах, запиши обе версии и кто что говорит.

Подбери 7 страниц для скриншотов — по одной на каждый шаг будущей карусели: статья, заголовок которой прямо про этот шаг. Лучше разные издания и без пэйволла.

Ответ — JSON:
{"topic": "тема по-русски одной фразой", "topicKey": "korotkiy-klyuch-latinicey", "angle": "что в истории известно и что скрывают — 2–3 предложения; последним предложением: кому читатель это перешлёт и с какими словами",
 "facts": [{"id": "f1", "claim": "утверждение по-русски", "quote": "точная цитата со страницы", "url": "https://…", "publisher": "CoinDesk", "date": "2026-10-24"}],
 "pages": [{"step": 1, "url": "https://…", "publisher": "…", "headline": "заголовок страницы"}]}
Фактов — 12–25, страниц — 7.`,
  };
}

export function writeTask(research: SidResearch, recentCovers: string[] = []): { system: string; user: string } {
  const recent = recentCovers.length ? `\n  Обложки прошлых каруселей, у новой другой предмет и другое место:\n${recentCovers.map((x) => `  · ${x}`).join("\n")}` : "";
  return {
    system: VOICE,
    user: `Напиши карусель по исследованию ниже. Опирайся только на его факты.

Формат — 9 слайдов: обложка, 7 шагов, финал. Пример хорошей карусели этого аккаунта (показаны 3 шага из 7) — пиши так же коротко, с цифрами и без воды:
${example()}

Поля:
- cover — громкий постер, как «ВЗЛОМАЛИ / BINANCE.» и под ним «УШЛО ДО $5,8 МЛРД.»: cover.title — 2–3 строки КАПСОМ по 1–2 слова, каждая до ${SID_LIMITS.coverLine - 1} знаков, на всю ширину, последняя строка выйдет акцентным цветом. Заголовок называет вещь, которая есть у самого читателя, и что с ней случилось, чтобы он узнал себя и подумал, кому это показать: «ШПИОН / В LEDGER.», «КРИПТА / НА IPHONE / ПРОПАДАЕТ.», «TELEGRAM / СМЕНИЛ / ТВОЙ КОШЕЛЁК.», «ЦБ ЗАКРЫЛ / ВЫВОД / НА КОШЕЛЁК.»; cover.accentLine — строка под ним с главной цифрой истории, до ${SID_LIMITS.coverAccent - 2} знаков («$2 МЛРД ИЗ ОАЭ.»); cover.pill — «СРОЧНО»; cover.hook — короткая фраза со стрелкой о том, что читатель сейчас проверит у себя или узнает: «Проверь, где ты покупал свой →», «Что будет с твоими монетами →», «Что известно и что скрывают →»;
- cover.scene — сцена обложки по-английски: ${COVER_SCENE}; надписей в кадре нет;${recent}
- steps — ровно 7, история по порядку: от события к открытому вопросу. В каждом шаге:
  label — «Источник · уточнение» до ${SID_LIMITS.label - 2} знаков, например «CoinDesk · 9 октября» или «Суд Нью-Йорка · дело 153119/2026»;
  title — заголовок в 2 строки до ${SID_LIMITS.title - 2} знаков, с точкой или вопросом в конце;
  body — 2–3 строки, 120–${SID_LIMITS.body - 5} знаков, 2–4 фрагмента **жирным**: цифры, имена, ключевые слова;
  pills — две плашки [«МЕТКА», «значение»]: метка КАПСОМ до ${SID_LIMITS.pillLabel - 1} знаков, значение до ${SID_LIMITS.pillValue - 1} знаков — факт из этого шага: цифра, дата, имя или статус («на паузе», «Draft», «не доказан»); если цифры нет, бери другой факт шага — «?» и «неизвестно» значением не бывают;
  next — продолжение фразы «Далее: …», строчными, до ${SID_LIMITS.next - 2} знаков; у седьмого шага — «сохрани»;
  icon — одно из: ${SID_ICONS.join(", ")};
  source — номер страницы в sources (с нуля): её скриншот встанет в окно шага, поэтому это страница про этот шаг; у каждого из семи шагов своя страница — одинаковых окон в карусели нет;
  facts — id фактов, на которых стоит шаг;
- final.black — 2 строки КАПСОМ до ${SID_LIMITS.finalLine - 1} знаков: кому переслать, с названием вещи из истории, чтобы читатель сразу вспомнил такого человека: «ПЕРЕШЛИ ТОМУ, / У КОГО LEDGER.», «ПЕРЕШЛИ ДРУГУ / С АЙФОНОМ.», «ПОКАЖИ ТОМУ, / КТО ДЕРЖИТ USDT.»; final.accent — 1–2 строки КАПСОМ до ${SID_LIMITS.finalLine - 3} знаков: вопрос к читателю; final.cards — 3 карточки [значок до ${SID_LIMITS.cardBadge} знаков, крупно до ${SID_LIMITS.cardTitle - 1} знаков, подпись до ${SID_LIMITS.cardSub - 1} знаков] — главные цифры истории; final.body — вопрос и «Пиши в комментариях.», до ${SID_LIMITS.finalBody - 10} знаков;
- пунктуация как в примере: пояснение идёт после двоеточия или новой фразой («Истец: бывший инженер Circle.», «Внутри: чип с eSIM.»), длинного тире в текстах карусели нет; слова пишутся целиком, без сокращений через дефис: «бывший инженер», а не «экс-инженер»;
- строки обложки и финала читаются каждая целым куском фразы: «ПЕРЕШЛИ ТОМУ, / У КОГО LEDGER.», «В КОШЕЛЬКАХ LEDGER / НАШЛИ ЧИП-ШПИОН.» — союз или предлог начинает следующую строку, а не заканчивает предыдущую;
- caption — подпись к посту в 2–3 строки: крючок с главными фактами, потом вопрос и «Пиши в комментариях.», последней строкой: кому переслать («Перешли тому, у кого кошелёк в Telegram.»). Без хэштегов, эмодзи, Telegram и обещаний что-то прислать;
- sources — сначала 7 страниц для скриншотов из pages исследования (по порядку шагов), затем другие использованные страницы: {url, title, publisher, date}.

Каждое число, дата, имя и цитата в тексте — из фактов исследования. Обвинения звучат как утверждения источника («по словам…», «по данным…»), рядом — ответ обвиняемой стороны, если он есть. Если источники расходятся, бери осторожную формулировку.

Ответ — один JSON в формате примера (в каждом шаге ещё поле "facts").

Исследование:
${JSON.stringify(research)}`,
  };
}

export function verifyTask(content: SidContent, research: SidResearch, pages: { step: number; url: string; text: string }[]): { system: string; user: string } {
  const texts = pages.map((p) => `=== Шаг ${p.step}, ${p.url}\n${p.text.slice(0, 6000)}`).join("\n\n");
  return {
    system: VOICE + " Сейчас ты — фактчекер карусели.",
    user: `Проверь каждое утверждение карусели — обложку, заголовки, тексты, плашки, финал и подпись — по фактам исследования и текстам страниц.
- Число, дата, сумма, имя и цитата совпадают с источником. Если в источнике иначе — исправь по источнику.
- Утверждение, которого нет ни в фактах, ни в текстах страниц, в карусели не остаётся: перепиши его до того, что источник действительно говорит, или убери деталь — в тексте, плашках, финальных карточках и подписи. Плашку с убранным значением замени другой плашкой из подтверждённых фактов этого шага.
- Обвинения звучат как утверждения источника; оценки («замяли», «скрыли») — только в вопросах.
- Длины полей, формат и пунктуацию сохраняй: пределы те же, что в карусели, пояснения через двоеточие, без длинного тире. Ничего не добавляй сверх источников. Поле source у шагов не меняй.
Ответ — JSON: {"content": <вся карусель в том же формате, уже без неподтверждённого>, "changes": ["что исправлено и почему"], "unsupported": [{"claim": "что не удалось подтвердить", "fragments": ["точный кусок текста, как он стоял в карусели до правки — например «26-cv-03686»"]}]}.

Карусель:
${JSON.stringify(content)}

Факты исследования:
${JSON.stringify(research.facts)}

Тексты страниц для скриншотов:
${texts}`,
  };
}

/** Точечная правка: не поместилось в вёрстку, плашка без настоящего значения, неподтверждённый кусок. */
export function fixTask(content: SidContent, problems: string[]): { system: string; user: string } {
  return {
    system: VOICE,
    user: `Исправь в карусели только перечисленное. Длинное — сократи, сохранив смысл; плашку без настоящего значения замени другой плашкой из фактов того же шага; неподтверждённый кусок убери или перепиши до подтверждённого — везде, где он стоит. Подтверждённые цифры, даты и имена не меняй, поле source у шагов не трогай, остальные поля оставь как есть.
${problems.map((p) => `- ${p}`).join("\n")}

Карусель:
${JSON.stringify(content)}

Ответ — JSON {"content": <вся карусель в том же формате>}.`,
  };
}
