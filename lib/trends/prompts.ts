// пробелы в конце строк уходят, пустые строки между абзацами остаются: по ним автор держит паузы
const str = (v: unknown, max = 2000) => (typeof v === "string" ? v.replace(/[ \t]+\n/g, "\n").trim().slice(0, max) : "");
const num = (v: unknown) => (typeof v === "number" && Number.isFinite(v) ? v : typeof v === "string" && v.trim() && Number.isFinite(Number(v)) ? Number(v) : null);

export function normalizeAnalysis(raw: any): TrendAnalysis {
  const id = num(raw?.formulaId);
  const formula = id === null ? undefined : hookById(id);
  return {
    formulaId: formula ? formula.id : null,
    formulaName: formula ? formula.name : str(raw?.formulaName, 80) || "Не размечена",
    hookSpoken: str(raw?.hookSpoken, 400),
    hookRu: str(raw?.hookRu, 400),
    hookScreen: str(raw?.hookScreen, 200),
    structure: (Array.isArray(raw?.structure) ? raw.structure : []).map((s: unknown) => str(s, 300)).filter(Boolean).slice(0, 8),
    seconds: num(raw?.seconds),
    ask: str(raw?.ask, 300),
    why: str(raw?.why, 1200),
    ...(formula ? {} : { shape: str(raw?.shape, 400) }),
    ...(str(raw?.story) ? { story: str(raw?.story, 800) } : {}),
    ...(raw?.fit === "sketch" || raw?.fit === "video" ? { fit: raw.fit } : {}),
  };
}

export function normalizeSketch(raw: any): SketchIdea {
  return { kind: "sketch", title: str(raw?.title, 80), plot: str(raw?.plot, 600), opening: str(raw?.opening, 200), formulaUse: str(raw?.formulaUse, 300) };
}

export function normalizeVideo(raw: any): VideoIdea {
  const hooks: HookOption[] = (Array.isArray(raw?.hooks) ? raw.hooks : []).slice(0, 3).map((h: any) => {
    const formula = hookById(num(h?.formulaId));
    return { formulaId: formula?.id ?? 0, formulaName: formula?.name ?? str(h?.formulaName, 80), spoken: str(h?.spoken, 300), screen: str(h?.screen, 120) };
  });
  const beats: Beat[] = (Array.isArray(raw?.beats) ? raw.beats : []).slice(0, 30).map((b: any) => ({
    from: num(b?.from) ?? 0, to: num(b?.to) ?? 0, say: str(b?.say, 400), screen: str(b?.screen, 120), shot: str(b?.shot, 200),
  }));
  const chosen = num(raw?.chosen);
  return {
    kind: "video", title: str(raw?.title, 80), topic: str(raw?.topic, 300), hooks,
    chosen: chosen !== null && chosen >= 0 && chosen < hooks.length ? Math.floor(chosen) : 0,
    script: str(raw?.script, 3000), beats, seconds: num(raw?.seconds) ?? (beats.at(-1)?.to ?? 0), loop: str(raw?.loop, 300),
  };
}

const words = (s: string) => s.split(/\s+/).filter((w) => /[\p{L}\p{N}]/u.test(w)).length;
const sentences = (s: string) => (s.match(/[.!?…]+(\s|$)/g) ?? []).length || (s.trim() ? 1 : 0);
const norm = (s: string) => s.toLowerCase().replace(/[^\p{L}\p{N}\s]/gu, " ").replace(/\s+/g, " ").trim();

/** Что в сюжете расходится с образцом — поручения на второй проход, сказанные как «как надо». */
export function sketchIssues(idea: SketchIdea): string[] {
  const issues: string[] = [];
  if (!idea.plot) issues.push("Напиши сюжет в plot: 2–3 предложения от первого лица владельца.");
  else if (sentences(idea.plot) > 3) issues.push("Сожми сюжет до 2–3 предложений: одна сцена, нарастание, один разворот, вывод.");
  if (!idea.title) issues.push("Дай название в 2–5 слов.");
  const n = words(idea.opening);
  if (n < 3 || n > 14) issues.push("Первая реплика — одна фраза на 4–12 слов, в которой видна вся ситуация.");
  return issues;
}

export function videoIssues(idea: VideoIdea): string[] {
  const issues: string[] = [];
  const ids = idea.hooks.map((h) => h.formulaId);
  if (idea.hooks.length !== 3 || ids.some((id) => !hookById(id)) || new Set(ids).size !== ids.length)
    issues.push("Дай три зацепки трёх разных формул из списка, с их номерами в formulaId.");
  for (const h of idea.hooks) {
    if (words(h.screen) > 6) issues.push(`Надпись «${h.screen}» сократи до шести слов: её читают за секунду.`);
    if (!h.spoken) issues.push("У каждой зацепки есть сказанная фраза spoken.");
  }
  if (idea.seconds < 15 || idea.seconds > 45) issues.push("Уложи ролик в 15–45 секунд.");
  const n = words(idea.script);
  if (n < 30 || n > 130) issues.push("Сценарий — 40–110 слов, чтобы он читался за 15–45 секунд.");
  const lead = idea.hooks[idea.chosen]?.spoken;
  if (lead && !norm(idea.script).startsWith(norm(lead).split(" ").slice(0, 3).join(" ")))
    issues.push("Сценарий начинается с выбранной зацепки слово в слово.");
  let at = 0;
  for (const b of idea.beats) {
    if (Math.abs(b.from - at) > 0.6) {
      issues.push("Кадры раскадровки идут подряд без дыр: каждый следующий начинается там, где кончился предыдущий.");
      break;
    }
    at = b.to;
  }
  if (idea.beats.some((b) => b.to - b.from > 4.01)) issues.push("Каждый кадр раскадровки — до 4 секунд: длинный раздели на два-три.");
  if (!idea.beats.length || Math.abs(at - idea.seconds) > 1) issues.push("Раскадровка покрывает ролик целиком, от 0 до seconds.");
  if (idea.beats.some((b) => words(b.screen) > 6)) issues.push("Надписи раскадровки — до шести слов.");
  return issues;
}

export const ideaIssues = (idea: Idea) => (idea.kind === "sketch" ? sketchIssues(idea) : videoIssues(idea));
